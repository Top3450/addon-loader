// Join a snippet onto the script, merging `import { a, b } from "x"` lines so no binding is declared twice
S.mergeJS = (base, add) => {
  const RX = /^\s*import\s*\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]\s*;?\s*$/gm;
  const mods = new Map(), order = [];
  const take = (src) => String(src || '').replace(RX, (m, names, mod) => {
    if (!mods.has(mod)) { mods.set(mod, new Set()); order.push(mod); }
    names.split(',').map(n => n.trim()).filter(Boolean).forEach(n => mods.get(mod).add(n));
    return '';
  }).trim();
  const body = [take(base), take(add)].filter(Boolean).join('\n\n');
  const head = order.map(m => `import { ${[...mods.get(m)].join(', ')} } from "${m}";`).join('\n');
  return (head ? head + '\n\n' : '') + body + '\n';
};
