S.Java.cmd = (c) => {
  let s = String(c).trim().replace(/^\/+/, '');
  let m;
  if ((m = s.match(/^effect\s+(\S+)\s+clear\s*$/))) return `effect clear ${m[1]}`;
  if ((m = s.match(/^effect\s+(?!give\b|clear\b)(\S+)\s+(\S+)(.*)$/))) return `effect give ${m[1]} ${m[2].includes(':') ? m[2] : 'minecraft:' + m[2]}${m[3]}`;
  if ((m = s.match(/^xp\s+(-?\d+)\s+(\S+)\s*$/))) return `xp add ${m[2]} ${m[1]}`;
  if ((m = s.match(/^xp\s+(-?\d+)L\s+(\S+)\s*$/i))) return `xp add ${m[2]} ${m[1]} levels`;
  return s;
};
